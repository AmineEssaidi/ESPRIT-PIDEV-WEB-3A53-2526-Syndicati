$dir = new RecursiveDirectoryIterator(__DIR__ . '/templates/frontend');
$ite = new RecursiveIteratorIterator($dir);
$files = new RegexIterator($ite, '/.*\.html\.twig$/', RegexIterator::GET_MATCH);

$count = 0;
foreach ($files as $file) {
    $path = $file[0];
    $content = file_get_contents($path);
    $original = $content;

    // Replace data-i18n="Key">Original Text</tag>
    // Or just data-i18n="Key" and we keep the original text, but we actually WANT to replace the text with {{ 'key'|trans }}
    // The pattern: `data-i18n="Key">Text<` or `data-i18n="Key">Text</`

    foreach ($map as $oldKey => $newKey) {
        // Find tags with data-i18n="$oldKey" and replace both attribute and inner text
        // e.g., <span data-i18n="Settings">Paramètres</span> -> <span>{{ 'settings.title'|trans }}</span>

        // This regex looks for data-i18n="oldKey" and the following >...< portion.
        // It's tricky with HTML. Let's just do a simple str_replace for the exact phrases if we can,
        // or a regex.

        $pattern = '/data-i18n="' . preg_quote($oldKey, '/') . '"([^>]*)>([^<]*)<\//i';
        $content = preg_replace_callback($pattern, function ($matches) use ($newKey) {
            // $matches[1] is the rest of the attributes
            // $matches[2] is the inner text
            return $matches[1] . '>{{ \'' . $newKey . '\'|trans }}</';
        }, $content);

        // Also handle self-closing or placeholder inputs if any: placeholder="Paramètres" data-i18n="Settings"
        $pattern2 = '/placeholder="([^"]*)"\s*data-i18n="' . preg_quote($oldKey, '/') . '"/i';
        $content = preg_replace($pattern2, 'placeholder="{{ \'' . $newKey . '\'|trans }}"', $content);

        $pattern3 = '/data-i18n="' . preg_quote($oldKey, '/') . '"\s*placeholder="([^"]*)"/i';
        $content = preg_replace($pattern3, 'placeholder="{{ \'' . $newKey . '\'|trans }}"', $content);
    }

    // Clean up empty data-i18n left behind (if the regex missed the exact structure because of line breaks)
    // Actually, maybe we can just remove `data-i18n="..."` everywhere.
    $content = preg_replace('/data-i18n="([^"]*)"/i', '', $content);

    if ($content !== $original) {
        file_put_contents($path, $content);
        echo "Updated $path\n";
        $count++;
    }
}

echo "Updated $count files.\n";
