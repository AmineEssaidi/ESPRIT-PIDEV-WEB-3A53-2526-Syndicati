        function translateAll(toLang) {
            document.querySelectorAll('[data-i18n]').forEach(function (el) {
                var key = el.getAttribute('data-i18n');
                var t;
                if (translations[toLang] && Object.prototype.hasOwnProperty.call(translations[toLang], key)) {
                    t = translations[toLang][key];
                } else if (translations['fr'] && Object.prototype.hasOwnProperty.call(translations['fr'], key)) {
                    t = translations['fr'][key];
                } else if (translations['en'] && Object.prototype.hasOwnProperty.call(translations['en'], key)) {
                    t = translations['en'][key];
                } else {
                    t = key; // fallback to the key itself if missing in all dictionaries
                }
                el.textContent = t;
            });
        }

        function initSmartTranslate(preferredLang) {
            translateAll(preferredLang);
        }

        document.addEventListener('DOMContentLoaded', function () {
            setTimeout(() => {
                let lang = localStorage.getItem('lang') || 'fr';
                initSmartTranslate(lang);
            }, 200);
        });

        window.SmartTranslate = { init: initSmartTranslate };
        window.translations = translations;

        window.setLanguage = function (newLang) {
            localStorage.setItem('lang', newLang);
            document.documentElement.setAttribute('lang', newLang);
            if (window.SmartTranslate) {
                window.SmartTranslate.init(newLang);
            }
            translateAll(newLang);
        };
